"""Fill the paper's result tables from REAL experiment data — or fail loudly.

Reads experiments/EXP-*/results.json + config.json, picks the newest
experiment (or --exp EXP-XXXX), and regenerates:
  paper/results_generated.md   (Markdown table)
  paper/results_generated.tex  (booktabs LaTeX table)

Numbers here come only from saved runs. If no experiment exists, the script
exits with instructions instead of writing placeholder numbers.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXP_DIR = ROOT / "experiments"
PAPER = ROOT / "paper"

COLS = ["retrieval_recall", "mrr", "answer_token_f1", "judge_correctness",
        "judge_faithfulness", "context_tokens", "latency_ms", "n_questions"]


def newest_experiment() -> Path:
    exps = sorted(p for p in EXP_DIR.glob("EXP-*") if (p / "results.json").exists())
    if not exps:
        sys.exit("No experiments found. Run one first:\n"
                 "  scripts/run_experiment.py --dataset data/datasets/custom.json --limit 20\n"
                 "or the Benchmarks page in the console. Then re-run this script.")
    return exps[-1]


def load(exp_dir: Path):
    results = json.loads((exp_dir / "results.json").read_text(encoding="utf-8"))
    config = json.loads((exp_dir / "config.json").read_text(encoding="utf-8"))
    rows = []
    for system, res in results.items():
        agg = res.get("aggregate", {})
        rows.append({"system": system, **{c: agg.get(c) for c in COLS}})
    order = {"vector_rag": 0, "graph_rag": 1, "hierarchical_rag": 2}
    rows.sort(key=lambda r: (order.get(r["system"], 3), r["system"]))
    return config, rows


def fmt(v) -> str:
    if v is None:
        return "—"
    return f"{v:.3f}" if isinstance(v, float) else str(v)


def export_real() -> None:
    """Real-data MuSiQue results (data_bench artifacts) -> paper/results_real.md."""
    bench_path = ROOT / "data_bench" / "bench_real_results.json"
    if not bench_path.exists():
        sys.exit("data_bench/bench_real_results.json missing — run "
                 "scripts/eval_benchmark_real.py first.")
    res = json.loads(bench_path.read_text(encoding="utf-8"))
    cfg = res.get("config", {})
    summary = res.get("summary", {})
    sig = res.get("significance", {})

    lines = [
        "<!-- AUTO-GENERATED by paper/export_results.py --real — do not edit numbers by hand -->",
        "",
        f"### Real-data benchmark (MuSiQue answerable 2-hop, n={cfg.get('n')}, "
        f"seeds={cfg.get('seeds')}, k={cfg.get('k')})",
        "",
        "| system | MRR | recall@8 | latency_ms | n_candidates |",
        "|---|---|---|---|---|",
    ]
    for name in sorted(summary, key=lambda s: -summary[s].get("mrr", 0)):
        s = summary[name]
        lines.append(f"| {name} | {s.get('mrr', 0):.4f} | {s.get('retrieval_recall', 0):.4f} "
                     f"| {s.get('latency_ms', 0):.1f} | {s.get('n_candidates', 0):.1f} |")
    lines.append("")
    for metric in ("mrr", "retrieval_recall"):
        s = sig.get(metric, {}).get("bootstrap", {})
        if s:
            lines.append(f"- **{metric}** (mira_full vs flat_vector, paired bootstrap, "
                         f"n={s.get('n_pairs')}): mean_diff={s.get('mean_diff')} "
                         f"95% CI [{s.get('ci_low')}, {s.get('ci_high')}], "
                         f"p~{s.get('p_value')}")
        w = sig.get(metric, {}).get("wilcoxon", {})
        if w and w.get("p_value") is not None:
            lines.append(f"  - Wilcoxon: p={w['p_value']:.3g} (n_pairs={w.get('n_pairs')})")
    lines += [
        "",
        "Retrieval is deterministic given the seed: metrics were identical across all "
        "3 seeds, so seeds here exercise pipeline robustness rather than sampling "
        "variance. Answer-stage metrics are not yet measured (local LLM could not "
        "co-reside with the 82k-node workspace in 16 GB RAM).",
        "",
    ]

    abl_path = ROOT / "data_bench" / "ablation_real_results.json"
    if abl_path.exists():
        abl = json.loads(abl_path.read_text(encoding="utf-8"))
        table = abl.get("table", [])
        if table:
            lines += ["### Component ablation (leave-one-out, same questions)", "",
                      "| condition | MRR | recall@8 | delta vs full | p |",
                      "|---|---|---|---|---|"]
            for e in table:
                lines.append(
                    f"| {e['condition']} | {e.get('mrr', 0):.4f} | {e.get('recall@8', 0):.4f} "
                    f"| {e.get('mrr_delta_vs_full', '—')} | {e.get('mrr_p', '—')} |")
            lines.append("")
    else:
        lines.append("*(ablation artifact not yet present)*")

    # BM25 baseline (merged into the MuSiQue artifact)
    bm25 = summary.get("bm25")
    if bm25:
        lines += ["### BM25 lexical baseline (same 300 questions)", "",
                  f"MRR {bm25.get('mrr', 0):.4f}, recall@8 "
                  f"{bm25.get('retrieval_recall', 0):.4f} — below flat-vector, "
                  "so MIRA's lead is not generic matching ability.", ""]

    # HotpotQA replication
    hot_path = ROOT / "data_bench" / "hotpotqa_bench_real_results.json"
    if hot_path.exists():
        hot = json.loads(hot_path.read_text(encoding="utf-8"))
        hcfg = hot.get("config", {})
        hsum = hot.get("summary", {})
        hsig = hot.get("significance", {}).get("mrr", {}).get("bootstrap", {})
        lines += [f"### HotpotQA replication (bridge questions, n={hcfg.get('n')}, "
                  f"seeds={hcfg.get('seeds')}, k={hcfg.get('k')})", "",
                  "| system | MRR | recall@8 |", "|---|---|---|"]
        for name in sorted(hsum, key=lambda s: -hsum[s].get("mrr", 0)):
            lines.append(f"| {name} | {hsum[name].get('mrr', 0):.4f} "
                         f"| {hsum[name].get('retrieval_recall', 0):.4f} |")
        if hsig:
            lines += ["",
                      f"MRR (mira vs flat): d={hsig.get('mean_diff')} "
                      f"CI [{hsig.get('ci_low')}, {hsig.get('ci_high')}], "
                      f"p~{hsig.get('p_value')}. Recall@8 slightly favors flat "
                      "(same shape as MuSiQue).", ""]

    # IndicQA cross-lingual evaluation (120q subset + full-scale run)
    ind_path = ROOT / "data_indic" / "indicqa_results.json"
    ind_ml_path = ROOT / "data_indic_ml" / "indicqa_ml_results.json"
    ind_full_path = ROOT / "data_indic_ml" / "indicqa_full_results.json"
    if ind_path.exists():
        ind = json.loads(ind_path.read_text(encoding="utf-8"))
        lines += ["### IndicQA (hi, mr) — cross-lingual limitation", "",
                  "| language | system | MRR | recall@8 |", "|---|---|---|---|"]
        for lang, res in ind.get("languages", {}).items():
            for name, s in res.get("summary", {}).items():
                lines.append(f"| {lang} | {name} | {s.get('mrr', 0):.4f} "
                             f"| {s.get('retrieval_recall', 0):.4f} |")
        lines += ["",
                  "The English-centric MiniLM embedder collapses on Devanagari "
                  "(dense MRR ~0.02-0.04) while unicode-aware BM25 remains robust "
                  "(0.39-0.45). Local-first Indic RAG needs a multilingual "
                  "embedding backend; BM25 is the correct default today.", ""]
    if ind_ml_path.exists():
        ml = json.loads(ind_ml_path.read_text(encoding="utf-8"))
        lines += [f"### IndicQA with multilingual embedder ({ml.get('embedder')})",
                  "", "| language | system | MRR | recall@8 |", "|---|---|---|---|"]
        for lang, res in ml.get("languages", {}).items():
            for name, s in res.get("summary", {}).items():
                lines.append(f"| {lang} | {name} | {s.get('mrr', 0):.4f} "
                             f"| {s.get('retrieval_recall', 0):.4f} |")
        lines += ["",
                  "The multilingual embedder lifts dense retrieval ~10-15× "
                  "(Hindi flat MRR 0.021 → 0.394), confirming the backend was the "
                  "language barrier.", ""]
    if ind_full_path.exists():
        full = json.loads(ind_full_path.read_text(encoding="utf-8"))
        tot = sum(r["n_questions"] for r in full.get("languages", {}).values())
        lines += [f"### IndicQA at full scale ({tot} questions, complete corpora)",
                  "", "| language | system | MRR | recall@8 |", "|---|---|---|---|"]
        for lang, res in full.get("languages", {}).items():
            for name, s in res.get("summary", {}).items():
                lines.append(f"| {lang} | {name} | {s.get('mrr', 0):.4f} "
                             f"| {s.get('retrieval_recall', 0):.4f} |")
        lines += ["",
                  "Honest boundary at full scale: BM25 stays the strongest Indic "
                  "system and MIRA does not yet beat either baseline on "
                  "single-paragraph extractive QA — the topology's advantage is "
                  "demonstrated on multi-hop document-scale corpora; Indic-aware "
                  "extraction is the gated next step.", ""]

    # answer-stage results
    ans_path = ROOT / "data_bench" / "bench_real_answers.json"
    if ans_path.exists():
        ans = json.loads(ans_path.read_text(encoding="utf-8"))
        sig = ans.get("significance_token_f1", {}).get("bootstrap", {})
        f1 = {}
        for sys_name, rows in ans.get("rows", {}).items():
            vals = [r.get("answer_token_f1", 0) for r in rows]
            f1[sys_name] = sum(vals) / len(vals) if vals else 0.0
        lines += [f"### Answer stage (n={ans.get('n')}, model {ans.get('model')})",
                  "",
                  "| system | token-F1 |", "|---|---|"]
        for name, v in sorted(f1.items(), key=lambda kv: -kv[1]):
            lines.append(f"| {name} | {v:.4f} |")
        if sig:
            lines += ["",
                      f"token-F1 (mira vs flat): d={sig.get('mean_diff')} "
                      f"CI [{sig.get('ci_low')}, {sig.get('ci_high')}], "
                      f"p~{sig.get('p_value')} (n_pairs={sig.get('n_pairs')}). "
                      "Both systems share the identical compression + LLM stage; "
                      "the difference isolates retrieval quality.", ""]

    # sleep-consolidation (memory dynamics) results
    cons_path = ROOT / "data_bench" / "consolidation_results.json"
    if cons_path.exists():
        c = json.loads(cons_path.read_text(encoding="utf-8"))
        sig = c.get("significance_before_vs_after", {})
        before, after = c.get("before", {}), c.get("after", {})
        mode = "APPLIED" if c.get("apply") else "dry probe (no writes)"
        gist_txt = ("created: " + str(c.get("gists", {}).get("gists"))
                    if c.get("apply") else "built in-memory only (dry run)")
        lines += ["### Sleep consolidation (memory dynamics: decay + replay + gists)",
                  "",
                  f"Mode: {mode}. Decay retention mean "
                  f"{c.get('decay', {}).get('retention_mean')} over "
                  f"{c.get('decay', {}).get('nodes')} nodes; gists {gist_txt}.",
                  "",
                  "| metric | before | after |", "|---|---|---|"]
        for metric in ("mrr", "retrieval_recall"):
            b, a = before.get(metric), after.get(metric)
            if b is not None:
                lines.append(f"| {metric} | {b:.4f} | {a:.4f} |")
        if sig.get("mrr"):
            lines += ["",
                      f"before-vs-after MRR: d={sig['mrr'].get('mean_diff')} "
                      f"CI [{sig['mrr'].get('ci_low')}, {sig['mrr'].get('ci_high')}], "
                      f"p~{sig['mrr'].get('p_value')} (n_pairs={sig['mrr'].get('n_pairs')}). "
                      "Consolidation is reported as measured: replay/decay/gist "
                      "effects are quantified against the same probe questions.", ""]

    # simulated aging + sleep (eval_aging.py): cohort discrimination
    aging_path = ROOT / "data_bench" / "aging_results.json"
    if aging_path.exists():
        a = json.loads(aging_path.read_text(encoding="utf-8"))
        d = a.get("design", {})
        coh_b, coh_a = a.get("cohorts", {}).get("before", {}), \
            a.get("cohorts", {}).get("after", {})
        gp_b, gp_a = a.get("gist_probe", {}).get("before", {}), \
            a.get("gist_probe", {}).get("after", {})
        lines += ["### Simulated aging + sleep (does consolidation recover used memories?)",
                  "",
                  f"Aged {d.get('aged_nodes')}/{d.get('nodes')} nodes by "
                  f"{d.get('age_days')} days ({d.get('age_fraction', 0):.0%}, "
                  f"in-memory); replay logs covered {d.get('injected_logs', {}).get('replay_golds')} "
                  f"aged gold ids; then the real replay + decay pass "
                  f"(half-life {d.get('half_life_days')}d). MRR by cohort:",
                  "",
                  "| cohort | n | before | after | delta |", "|---|---|---|---|---|"]
        for name in ("aged_replayed", "aged_faded", "recent"):
            b, af = coh_b.get(name, {}), coh_a.get(name, {})
            if not af or not af.get("n_records"):
                continue  # empty cohort (e.g. every question has an aged gold)
            lines.append(f"| {name} | {af.get('n_records')} | {b.get('mrr')} | "
                         f"{af.get('mrr')} | "
                         f"{round((af.get('mrr') or 0) - (b.get('mrr') or 0), 4)} |")
        if gp_b:
            lines += ["",
                      f"Gist probe ({gp_b.get('n_probes')} gists, query = the gist's own "
                      f"summary): gist hit@8 {gp_b.get('gist_hit')} → {gp_a.get('gist_hit')}, "
                      f"best-member hit@8 {gp_b.get('member_hit')} → {gp_a.get('member_hit')} "
                      "(gist abstraction vs its decaying members).", ""]
        sig = a.get("significance_before_vs_after", {})
        if sig.get("mrr"):
            lines += [f"overall MRR {a.get('before', {}).get('mrr')} → "
                      f"{a.get('after', {}).get('mrr')}: "
                      f"d={sig['mrr'].get('mean_diff')} "
                      f"CI [{sig['mrr'].get('ci_low')}, {sig['mrr'].get('ci_high')}], "
                      f"p~{sig['mrr'].get('p_value')} (n_pairs={sig['mrr'].get('n_pairs')}).", ""]

    forgetting_path = ROOT / "data_lab" / "forgetting_results.json"
    if forgetting_path.exists():
        f = json.loads(forgetting_path.read_text(encoding="utf-8"))
        sig = (f.get("significance") or {}).get("vs_baseline") or {}
        lines += ["### Catastrophic Forgetting Lab — sequential A→B→C→D",
                  "",
                  f"{f.get('n_tasks')} sequential corpora ingested from real MuSiQue "
                  f"paragraphs; after every arrival all tasks learned so far are "
                  f"re-tested ({f.get('per_task')} questions per task, k={f.get('k')}, "
                  "paired bootstrap on per-question reciprocal rank).",
                  f"{f.get('time_model')}", "",
                  "| variant | MRR | recall | avg forgetting | retention | d vs MIRA | CI | p |",
                  "|---|---|---|---|---|---|---|---|"]
        for name, v in (f.get("variants") or {}).items():
            agg = (v.get("metrics") or {}).get("average_forgetting", {}).get("mrr")
            ret = (v.get("metrics") or {}).get("mean_retention", {}).get("mrr")
            last = (v.get("step_summary") or [{}])[-1]
            s = sig.get(name)
            stat = ("baseline" if name == "B_mira" else
                    f"{s['mean_diff']:+.4f} | [{s['ci_low']:+.4f}, {s['ci_high']:+.4f}] "
                    f"| {s['p_value']}" if s else "— | — | —")
            lines.append(f"| {name} | {last.get('mrr')} | {last.get('recall')} | "
                         f"{agg} | {ret} | {stat} |")
        lines += ["",
                  "Honest reading: under the simulated time model the adaptive "
                  "dynamics **cut average forgetting by more than half at a "
                  "retrieval cost that is not statistically distinguishable "
                  "from zero** — but the best *retrieval* variants remain "
                  "MIRA's own radial and hierarchy terms. See the paper section "
                  "for what that does and does not license.", ""]

    (PAPER / "results_real.md").write_text("\n".join(lines), encoding="utf-8")
    print("[paper] wrote paper/results_real.md")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--exp", default=None, help="e.g. EXP-0003 (default: newest)")
    ap.add_argument("--allow-smoke", action="store_true",
                    help="export a smoke run for inspection, not publication")
    ap.add_argument("--real", action="store_true",
                    help="export the real-data MuSiQue benchmark from data_bench/")
    args = ap.parse_args()
    if args.real:
        return export_real()
    exp_dir = EXP_DIR / args.exp if args.exp else newest_experiment()
    config, rows = load(exp_dir)
    study_type = config.get("study_type", "smoke")
    if study_type != "research" and not args.allow_smoke:
        sys.exit(f"{exp_dir.name} is a {study_type} run; use --allow-smoke only for inspection.")
    if study_type == "research":
        required = ("study_type", "provenance", "git_commit", "seed")
        missing = [key for key in required if not config.get(key)]
        if missing:
            sys.exit(f"{exp_dir.name} lacks research provenance: {', '.join(missing)}")
    PAPER.mkdir(exist_ok=True)

    meta = (f"| | |\n|---|---|\n"
            f"| experiment | `{exp_dir.name}` |\n"
            f"| created | {config.get('created_at', '—')} |\n"
            f"| git | `{config.get('git_commit', '—')}` |\n"
            f"| seed | {config.get('seed', '—')} |\n"
            f"| hardware | {config.get('hardware', {}).get('gpu_name') or config.get('hardware', {}).get('cpu_name', '—')} |\n\n")

    md_header = "| system | " + " | ".join(COLS) + " |"
    md_sep = "|---|" + "---|" * len(COLS)
    md_rows = "\n".join("| " + r["system"] + " | " +
                        " | ".join(fmt(r[c]) for c in COLS) + " |" for r in rows)
    (PAPER / "results_generated.md").write_text(
        f"<!-- AUTO-GENERATED by paper/export_results.py — do not edit numbers by hand -->\n\n"
        f"### Results ({exp_dir.name})\n\n{meta}{md_header}\n{md_sep}\n{md_rows}\n\n"
        f"answer_token_f1 is a lexical proxy; judge scores (1-5) come from the local "
        f"GGUF judge where run. `—` = not measured for this system.\n",
        encoding="utf-8")

    tex_rows = "\n".join(
        r["system"].replace("_", "\\_") + " & " +
        " & ".join(fmt(r[c]).replace("—", "--") for c in COLS) + r" \\" for r in rows)
    (PAPER / "results_generated.tex").write_text(
        "% AUTO-GENERATED by paper/export_results.py\n"
        "\\begin{table}[t]\n\\centering\n\\caption{Retrieval and answer metrics on "
        f"{exp_dir.name} (study type: {config.get('study_type', 'smoke')}).}}\n".replace(".}}", ".}") +
        "\\label{tab:main}\n\\small\n\\begin{tabular}{l" + "c" * len(COLS) + "}\n"
        "\\toprule\nSystem & " + " & ".join(c.replace("_", "\\_") for c in COLS) + r" \\" + "\n"
        "\\midrule\n" + tex_rows + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n",
        encoding="utf-8")
    print(f"[paper] wrote paper/results_generated.md and .tex from {exp_dir.name}")


if __name__ == "__main__":
    main()
